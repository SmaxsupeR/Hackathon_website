const tables: Record<Language, Strings> = { ru, en };

function pluralIndex(lang: Language, n: number): number {
  if (lang === 'en') return n === 1 ? 0 : 1;
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return 0;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 1;
  return 2;
}

export function translate(lang: Language, key: StringKey, params?: Record<string, string | number>): string {
  const entry = tables[lang][key] as string | string[];
  let text = typeof entry === 'string' ? entry : entry[Math.min(entry.length - 1, pluralIndex(lang, Number(params?.n ?? 0)))];
  if (params) for (const [k, v] of Object.entries(params)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

export type T = (key: StringKey, params?: Record<string, string | number>) => string;

export function useT(): T {
  const lang = useApp((s) => s.settings.language);
  return useCallback((key, params) => translate(lang, key, params), [lang]);
}

const UNITS: Record<Language, Record<string, string>> = {
  ru: { m: ' мин', h: ' ч', d: ' дн', mo: ' мес', y: ' г' },
  en: { m: 'm', h: 'h', d: 'd', mo: 'mo', y: 'y' },
};

/** Formats a review interval with localized units, for example "4 дн". */
export function useInterval(): (ms: number) => string {
  const lang = useApp((s) => s.settings.language);
  return useCallback(
    (ms) => {
      const text = formatInterval(ms);
      const unit = text.replace(/[\d.]/g, '');
      return text.slice(0, text.length - unit.length) + (UNITS[lang][unit] ?? unit);
    },
    [lang],
  );
}

